export function explicitForbid(w: string): string[] {
  const f = SHLYAPA_WORDS.find((x) => x.w === w);
  return f?.f ?? [];
}

// Два «родственных» слова, если одно содержит другое или общий prefix >= 3
export function relatedWord(guess: string, secret: string): boolean {
  const a = guess.toLowerCase().trim();
  const b = secret.toLowerCase().trim();
  if (a === b) return true;
  if (b.includes(a) || a.includes(b)) return a.length >= 3;
  const pref = a.slice(0, 3);
  if (pref.length >= 3 && b.startsWith(pref)) return true;
  return false;
}

